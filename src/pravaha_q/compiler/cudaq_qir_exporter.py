"""
NVIDIA CUDA-Q Python Kernel & LLVM QIR Exporter (Driven by QuantumCircuitIR)
============================================================================
Emits executable NVIDIA CUDA-Q (`@cudaq.kernel`) source code and QIR resource
counts directly from the canonical `QuantumCircuitIR`.
"""

from __future__ import annotations

from dataclasses import dataclass

from pravaha_q.compiler.circuit_ir import QuantumCircuitIR
from pravaha_q.compiler.paulihedral_router import compile_paulihedral_schedule
from pravaha_q.math_engine.ising_spin_glass import IsingSpinGlass


@dataclass(frozen=True)
class QIRResourceProfile:
    """Quantum Intermediate Representation (QIR) hardware resource summary."""

    profile_version: str
    num_qubits_required: int
    num_classical_registers: int
    quantum_instruction_count: int
    two_qubit_entangling_count: int
    supports_base_profile: bool


def circuit_ir_to_cudaq_kernel(
    circuit: QuantumCircuitIR,
) -> tuple[str, QIRResourceProfile]:
    """Serialize any canonical `QuantumCircuitIR` directly to an NVIDIA CUDA-Q kernel."""
    n = circuit.num_qubits
    lines: list[str] = [
        '"""Auto-generated by PravahaQ v0.1.0 — NVIDIA CUDA-Q Hybrid Kernel."""',
        "import cudaq",
        "",
        "@cudaq.kernel",
        "def pravaha_bf_dcqo_kernel() -> None:",
        f"    q = cudaq.qvector({n})",
    ]

    for op in circuit.ops:
        g = op.name
        if g == "H":
            lines.append(f"    h(q[{op.qubits[0]}])")
        elif g == "X":
            lines.append(f"    x(q[{op.qubits[0]}])")
        elif g in ("RX", "RY", "RZ"):
            lines.append(
                f"    {g.lower()}({float(op.params[0]):.6f}, q[{op.qubits[0]}])"
            )
        elif g == "CX":
            lines.append(f"    x.ctrl(q[{op.qubits[0]}], q[{op.qubits[1]}])")
        elif g == "SWAP":
            lines.append(f"    swap(q[{op.qubits[0]}], q[{op.qubits[1]}])")

    lines.append("    mz(q)")
    total_inst = len(circuit.ops) + n
    qir_profile = QIRResourceProfile(
        profile_version="QIR-Base-Profile-v1.0",
        num_qubits_required=n,
        num_classical_registers=n,
        quantum_instruction_count=total_inst,
        two_qubit_entangling_count=circuit.count_2q_gates(),
        supports_base_profile=True,
    )
    return "\n".join(lines) + "\n", qir_profile


def export_cudaq_kernel_source(
    ising: IsingSpinGlass,
    gamma: float = 0.45,
    beta: float = 0.30,
) -> tuple[str, QIRResourceProfile]:
    """Compile IsingSpinGlass to an algebraically canceled QuantumCircuitIR and emit CUDA-Q."""
    report = compile_paulihedral_schedule(
        ising, cost_gamma=gamma, mixer_beta=beta
    )
    assert report.optimized_ir is not None
    return circuit_ir_to_cudaq_kernel(report.optimized_ir)
