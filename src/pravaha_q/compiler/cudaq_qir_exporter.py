"""
NVIDIA CUDA-Q Python Kernel & LLVM QIR Profile Exporter
=======================================================
Emits executable NVIDIA CUDA-Q (`@cudaq.kernel`) source code and a structured
Quantum Intermediate Representation (QIR) instruction manifest for hybrid
GPU-QPU supercomputing nodes (e.g., Grace Hopper + QPU).
"""

from __future__ import annotations

from dataclasses import dataclass

from pravaha_q.algorithms.agp_commutator import compute_analytical_agp_schedule
from pravaha_q.compiler.paulihedral_router import compile_paulihedral_schedule
from pravaha_q.math_engine.ising_spin_glass import IsingSpinGlass


@dataclass(frozen=True)
class QIRResourceProfile:
    """Quantum Intermediate Representation (QIR) hardware resource summary."""

    profile_version: str
    num_qubits_required: int
    num_classical_registers: int
    quantum_instruction_count: int
    two_qubit_entangling_count: int
    supports_base_profile: bool


def export_cudaq_kernel_source(
    ising: IsingSpinGlass,
    gamma: float = 0.45,
    beta: float = 0.30,
) -> tuple[str, QIRResourceProfile]:
    """
    Generate an executable NVIDIA CUDA-Q `@cudaq.kernel` Python module string
    and its corresponding LLVM QIR Base Profile resource summary.
    """
    n = ising.num_qubits
    h_norm, _, _ = ising.normalized_coefficients()
    agp = compute_analytical_agp_schedule(ising)
    pauli_report = compile_paulihedral_schedule(ising)
    scale = max(ising.spectral_scale, 1e-9)

    lines: list[str] = [
        '"""Auto-generated by PravahaQ v0.1.0 — NVIDIA CUDA-Q Hybrid Kernel."""',
        "import cudaq",
        "",
        "@cudaq.kernel",
        "def pravaha_bf_dcqo_kernel() -> None:",
        f"    q = cudaq.qvector({n})",
        "    h(q)",
        "",
        "    # Counterdiabatic AGP 1-Body & 2-Body Impulse",
    ]
    inst_count = n
    entangling_count = 0

    for i, y_ang in sorted(agp.y_1body_angles.items()):
        lines.append(f"    ry({2.0 * y_ang:.6f}, q[{i}])")
        inst_count += 1

    for (i, j), yz_ang in sorted(agp.yz_2body_angles.items()):
        lines.append(f"    rx(1.570796, q[{i}])")
        lines.append(f"    x.ctrl(q[{i}], q[{j}])")
        lines.append(f"    rz({2.0 * yz_ang:.6f}, q[{j}])")
        lines.append(f"    x.ctrl(q[{i}], q[{j}])")
        lines.append(f"    rx(-1.570796, q[{i}])")
        inst_count += 5
        entangling_count += 2

    lines.append("")
    lines.append("    # Vaisheshika 3-Local HUBO Cost Layer")
    for i, h_val in sorted(h_norm.items()):
        lines.append(f"    rz({2.0 * gamma * h_val:.6f}, q[{i}])")
        inst_count += 1

    for supp, raw_val in pauli_report.ordered_pauli_schedule:
        angle = 2.0 * gamma * (raw_val / scale)
        if len(supp) == 2:
            u, v = supp
            lines.append(f"    x.ctrl(q[{u}], q[{v}])")
            lines.append(f"    rz({angle:.6f}, q[{v}])")
            lines.append(f"    x.ctrl(q[{u}], q[{v}])")
            inst_count += 3
            entangling_count += 2
        elif len(supp) == 3:
            u, v, w = supp
            lines.append(f"    x.ctrl(q[{u}], q[{v}])")
            lines.append(f"    x.ctrl(q[{v}], q[{w}])")
            lines.append(f"    rz({angle:.6f}, q[{w}])")
            lines.append(f"    x.ctrl(q[{v}], q[{w}])")
            lines.append(f"    x.ctrl(q[{u}], q[{v}])")
            inst_count += 5
            entangling_count += 4

    lines.append("")
    lines.append("    # Transverse Mixer & Measurement")
    for i in range(n):
        lines.append(f"    rx({-2.0 * beta:.6f}, q[{i}])")
        inst_count += 1

    lines.append("    mz(q)")
    inst_count += n

    qir_profile = QIRResourceProfile(
        profile_version="QIR-Base-Profile-v1.0",
        num_qubits_required=n,
        num_classical_registers=n,
        quantum_instruction_count=inst_count,
        two_qubit_entangling_count=entangling_count,
        supports_base_profile=True,
    )
    return "\n".join(lines) + "\n", qir_profile
